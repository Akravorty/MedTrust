export function translate(lang: LangCode, key: Key): string {
  return STRINGS[lang]?.[key] ?? EN[key];
}

interface I18nValue {
  lang: LangCode;
  info: LangInfo;
  setLang: (l: LangCode) => void;
  t: (key: Key) => string;
}

const DEFAULT_INFO = LANGUAGES[0];
const I18nContext = createContext<I18nValue>({
  lang: 'en',
  info: DEFAULT_INFO,
  setLang: () => {},
  t: (k) => EN[k],
});

const STORAGE_KEY = 'meditrust.lang';

function loadLang(): LangCode {
  try {
    const saved = localStorage.getItem(STORAGE_KEY) as LangCode | null;
    if (saved && LANGUAGES.some((l) => l.code === saved)) return saved;
  } catch { /* storage blocked */ }
  return 'en';
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<LangCode>(loadLang);
  const info = LANGUAGES.find((l) => l.code === lang) ?? DEFAULT_INFO;

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = info.rtl ? 'rtl' : 'ltr';
  }, [lang, info.rtl]);

  const value = useMemo<I18nValue>(
    () => ({
      lang,
      info,
      setLang: (l) => {
        setLangState(l);
        try { localStorage.setItem(STORAGE_KEY, l); } catch { /* ignore */ }
      },
      t: (key) => translate(lang, key),
    }),
    [lang, info],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
